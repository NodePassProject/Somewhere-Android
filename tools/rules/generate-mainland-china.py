#!/usr/bin/env python3
"""Generates the mainland-China policy rule set from the inputs in SOURCES.

Every line of the output is DIRECT: the set says what may skip the tunnel,
never what must take it. Domains become DOMAIN-SUFFIX rules, IPv4 blocks are
collapsed into IP-CIDR, IPv6 into IP-CIDR6. The output is sorted and carries
no timestamp other than the inputs', so two runs over the same inputs produce
the same bytes.

Usage:
  tools/rules/generate-mainland-china.py                 # fetch, verify, write
  tools/rules/generate-mainland-china.py --check         # regenerate and compare
  tools/rules/generate-mainland-china.py --apnic F --domains F   # local inputs
"""

import argparse
import gzip
import hashlib
import ipaddress
import pathlib
import sys
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
ASSET = HERE.parent.parent / "app/src/main/assets/rules/policy/mainland-china.list"


def sources() -> dict:
    values = {}
    for line in (HERE / "SOURCES").read_text().splitlines():
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            values[key] = value
    return values


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def verified(data: bytes, want: str, what: str) -> bytes:
    got = hashlib.sha256(data).hexdigest()
    if got != want:
        sys.exit(f"{what}: sha256 {got}, SOURCES pins {want}")
    return data


def cn_networks(apnic: str):
    v4, v6 = [], []
    for line in apnic.splitlines():
        fields = line.split("|")
        if len(fields) < 7 or fields[1] != "CN" or fields[6] not in ("allocated", "assigned"):
            continue
        if fields[2] == "ipv4":
            start = ipaddress.IPv4Address(fields[3])
            end = start + int(fields[4]) - 1
            v4.extend(ipaddress.summarize_address_range(start, end))
        elif fields[2] == "ipv6":
            v6.append(ipaddress.IPv6Network(f"{fields[3]}/{fields[4]}"))
    return sorted(ipaddress.collapse_addresses(v4)), sorted(ipaddress.collapse_addresses(v6))


def domains(conf: str):
    names = set()
    for line in conf.splitlines():
        line = line.strip()
        if not line.startswith("server=/"):
            continue
        name = line.split("/")[1].strip(".").lower()
        if name and all(part for part in name.split(".")):
            names.add(name)
    # A name already covered by a shorter suffix in the set adds nothing.
    return sorted(n for n in names if not any(".".join(n.split(".")[i:]) in names for i in range(1, n.count(".") + 1)))


def render(src: dict, v4, v6, names) -> str:
    header = [
        "# name: Mainland China",
        f"# source: APNIC delegated statistics; {src['CHINA_LIST_REPO'].removeprefix('https://github.com/')}",
        f"# revision: {src['APNIC_URL'].rsplit('/', 1)[1]}; {src['CHINA_LIST_COMMIT'][:12]}",
        f"# licence: {src['APNIC_LICENCE']}; {src['CHINA_LIST_LICENCE']}",
        "# date: {0}-{1}-{2}".format(*(lambda d: (d[:4], d[4:6], d[6:8]))(src["APNIC_URL"].rsplit("-", 1)[1][:8])),
        "#",
        "# Destinations in mainland China, sent DIRECT when the user turns this set on",
        "# in Rules mode. Generated by tools/rules/generate-mainland-china.py from the",
        "# inputs pinned in tools/rules/SOURCES; edit those, never this file.",
        "#",
        "# Addresses are where APNIC first allocated a block, not where it is used",
        "# today, and domains are those whose authoritative servers are in mainland",
        "# China. Both are approximations, which is why the set only ever says DIRECT:",
        "# a wrong entry sends one site around the tunnel, never into it.",
        f"# {len(names)} domains, {len(v4)} IPv4 and {len(v6)} IPv6 networks.",
        "",
    ]
    body = [f"DOMAIN-SUFFIX,{n},DIRECT" for n in names]
    body += [f"IP-CIDR,{net},DIRECT" for net in v4]
    body += [f"IP-CIDR6,{net},DIRECT" for net in v6]
    return "\n".join(header + body) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--apnic")
    parser.add_argument("--domains")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    src = sources()

    apnic = pathlib.Path(args.apnic).read_bytes() if args.apnic else fetch(src["APNIC_URL"])
    apnic = gzip.decompress(verified(apnic, src["APNIC_SHA256"], "APNIC"))
    raw = "https://raw.githubusercontent.com/{}/{}/{}".format(
        src["CHINA_LIST_REPO"].removeprefix("https://github.com/"), src["CHINA_LIST_COMMIT"], src["CHINA_LIST_FILE"])
    conf = pathlib.Path(args.domains).read_bytes() if args.domains else fetch(raw)
    conf = verified(conf, src["CHINA_LIST_SHA256"], "china list")

    v4, v6 = cn_networks(apnic.decode())
    text = render(src, v4, v6, domains(conf.decode()))
    if args.check:
        if ASSET.read_text() != text:
            sys.exit(f"{ASSET} does not match its inputs; regenerate it")
        print(f"OK  {ASSET.name} matches tools/rules/SOURCES")
        return 0
    ASSET.parent.mkdir(parents=True, exist_ok=True)
    ASSET.write_text(text)
    print(f"wrote {ASSET} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
